def _render_svg_pixmap(svg_inner, color, size):
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 24 24" fill="none" stroke="{color}" stroke-width="2" '
        f'stroke-linecap="round" stroke-linejoin="round">{svg_inner}</svg>'
    ).encode("utf-8")
    renderer = QSvgRenderer(svg)
    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.transparent)
    if renderer.isValid():
        painter = QPainter(pixmap)
        renderer.render(painter)
        painter.end()
    return pixmap


def get_icon(name, color="#cbd5e1", selected_color="#ffffff", size=20):
    """Return a crisp vector QIcon for the given icon name."""
    svg_inner = _ICON_PATHS.get(name)
    if not svg_inner:
        return QIcon()
    icon = QIcon()
    icon.addPixmap(_render_svg_pixmap(svg_inner, color, size), QIcon.Normal)
    if selected_color:
        icon.addPixmap(_render_svg_pixmap(svg_inner, selected_color, size), QIcon.Selected)
    return icon
